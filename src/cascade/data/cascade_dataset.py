"""Assemble a CASCADE training sample: GRN graph + per-node features + labels + splits.

A sample is the whole transcript graph at once (transductive): one GRN over N
transcript nodes, a per-node K=9 concept feature matrix, a per-node measured
log2 fold-change label, and boolean train / val / test masks. Two split modes
are supported: the standard random node split and a held-out-gene split that
keeps whole genes out of val / test.

The real data path joins GSE184929 log2FC labels (loaded by
:mod:`cascade.data.geo`) with the per-transcript concept features from
:mod:`cascade.features` onto the STRING GRN nodes. That join needs a transcript
identifier map that is not wired yet, so for now this module supports a
``synthetic`` mode (deterministic features and a propagated-signal label, used by
the smoke train and the tests) and a ``node_table`` mode that reads a precomputed
parquet. The synthetic labels are generated by propagating a linear function of
the features through P_alpha, so the model has a real signal to fit.

This module is pure numpy / scipy (no torch) so it can be exercised in the
lightweight CI image.
"""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass
from typing import Any

import numpy as np
import scipy.sparse as sp

from cascade.features import concept_layout
from cascade.verify.containment import propagate

from .string_grn import load_string_grn


@dataclass(frozen=True)
class CascadeData:
    """A fully assembled transductive CASCADE sample."""

    features: np.ndarray  # [N, F]
    feature_names: list[str]
    S: sp.csr_matrix  # symmetric-normalized GRN adjacency
    edge_index: np.ndarray  # [2, E]
    edge_weight: np.ndarray  # [E]
    labels: np.ndarray  # [N] measured (or synthetic) log2FC
    gene: np.ndarray  # [N] gene-group id per node
    train_mask: np.ndarray  # [N] bool
    val_mask: np.ndarray
    test_mask: np.ndarray
    meta: dict[str, Any]

    @property
    def num_nodes(self) -> int:
        return self.features.shape[0]

    @property
    def num_features(self) -> int:
        return self.features.shape[1]


def _cfg_get(cfg: Mapping[str, Any], key: str, default: Any = None) -> Any:
    """Read a key from a dict or an omegaconf DictConfig uniformly."""
    if hasattr(cfg, "get"):
        return cfg.get(key, default)
    return getattr(cfg, key, default)


def _synthetic_graph(n: int, edge_p: float, rng: np.random.Generator) -> sp.csr_matrix:
    """Random symmetric-normalized graph with a connecting cycle."""
    w = rng.random((n, n)) * (rng.random((n, n)) < edge_p)
    w = np.triu(w, 1)
    # Add a ring so the graph is connected and propagation actually spreads.
    for i in range(n):
        w[i, (i + 1) % n] = max(w[i, (i + 1) % n], 0.5)
    w = np.triu(w, 1)
    w = w + w.T
    deg = w.sum(axis=1)
    dinv = np.where(deg > 0, 1.0 / np.sqrt(deg), 0.0)
    s = dinv[:, None] * w * dinv[None, :]
    return sp.csr_matrix(s)


def _make_splits(
    split_cfg: Mapping[str, Any], n: int, gene: np.ndarray, rng: np.random.Generator
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    mode = _cfg_get(split_cfg, "mode", "standard")
    val_frac = float(_cfg_get(split_cfg, "val_frac", 0.2))
    test_frac = float(_cfg_get(split_cfg, "test_frac", 0.2))

    train = np.zeros(n, dtype=bool)
    val = np.zeros(n, dtype=bool)
    test = np.zeros(n, dtype=bool)

    if mode == "standard":
        perm = rng.permutation(n)
        n_test = max(1, int(round(test_frac * n)))
        n_val = max(1, int(round(val_frac * n)))
        n_test = min(n_test, n - 2)
        n_val = min(n_val, n - 1 - n_test)
        test[perm[:n_test]] = True
        val[perm[n_test : n_test + n_val]] = True
        train[perm[n_test + n_val :]] = True
    elif mode == "held_out_gene":
        genes = np.unique(gene)
        rng.shuffle(genes)
        g = len(genes)
        n_test_g = max(1, int(round(test_frac * g)))
        n_val_g = max(1, int(round(val_frac * g)))
        n_test_g = min(n_test_g, g - 2) if g >= 3 else 1
        n_val_g = min(n_val_g, g - 1 - n_test_g) if g - 1 - n_test_g >= 1 else 1
        test_g = set(genes[:n_test_g].tolist())
        val_g = set(genes[n_test_g : n_test_g + n_val_g].tolist())
        for i in range(n):
            if gene[i] in test_g:
                test[i] = True
            elif gene[i] in val_g:
                val[i] = True
            else:
                train[i] = True
    else:
        raise ValueError(f"unknown split mode {mode!r}; use 'standard' or 'held_out_gene'")

    if not train.any():
        raise ValueError("empty train split; loosen val/test fractions or use more nodes")
    return train, val, test


def build_cascade_data(cfg: Mapping[str, Any], seed: int) -> CascadeData:
    """Assemble a :class:`CascadeData` sample from a dataset config and a seed.

    Recognized config keys: ``graph`` (path or ``"synthetic"``), ``threshold``,
    ``cache``, ``n_nodes`` / ``edge_p`` (synthetic graph), ``synthetic`` (bool),
    ``synthetic_alpha`` / ``synthetic_noise``, ``node_table`` (parquet path), and
    a ``split`` block (``mode``, ``val_frac``, ``test_frac``, ``n_genes``).
    """
    rng = np.random.default_rng(seed)

    graph = str(_cfg_get(cfg, "graph", "synthetic"))
    if graph in ("synthetic", "none", "None"):
        n_nodes = int(_cfg_get(cfg, "n_nodes", 24))
        S = _synthetic_graph(n_nodes, float(_cfg_get(cfg, "edge_p", 0.35)), rng)
        nodes = [f"syn_{i}" for i in range(n_nodes)]
    else:
        grn = load_string_grn(
            graph,
            cache_root=_cfg_get(cfg, "cache"),
            threshold=int(_cfg_get(cfg, "threshold", 700)),
        )
        S = grn.S
        nodes = grn.nodes

    n = S.shape[0]
    coo = S.tocoo()
    edge_index = np.vstack([coo.row, coo.col]).astype(np.int64)
    edge_weight = coo.data.astype(np.float32)

    layout = concept_layout()
    synthetic = bool(_cfg_get(cfg, "synthetic", True))
    split_cfg = _cfg_get(cfg, "split", {})

    if synthetic:
        n_feat = layout.total_dim
        features = rng.standard_normal((n, n_feat)).astype(np.float32)
        feature_names = list(layout.feature_names)

        # Label = P_alpha applied to a linear readout of the features, plus noise.
        w = rng.standard_normal(n_feat)
        x0 = features @ w
        x0 = (x0 - x0.mean()) / (x0.std() + 1e-8)
        alpha = float(_cfg_get(cfg, "synthetic_alpha", 0.2))
        y = propagate(S, x0, alpha=alpha, num_steps=64)
        y = y + rng.standard_normal(n) * float(_cfg_get(cfg, "synthetic_noise", 0.05))
        labels = y.astype(np.float32)

        n_genes = int(_cfg_get(split_cfg, "n_genes", max(2, n // 3)))
        gene = rng.integers(0, max(1, n_genes), size=n)
    else:
        node_table = _cfg_get(cfg, "node_table")
        if node_table is None:
            raise ValueError(
                "non-synthetic mode requires 'node_table' (a parquet with feature "
                "columns, a 'log2fc' label, and a 'gene' column). The GSE184929 / "
                "STRING join that produces it is not wired yet; see the module docstring."
            )
        import pandas as pd

        df = pd.read_parquet(node_table)
        feature_names = [c for c in layout.feature_names if c in df.columns]
        features = df[feature_names].to_numpy(dtype=np.float32)
        labels = df["log2fc"].to_numpy(dtype=np.float32)
        gene = df.get("gene", pd.Series(np.arange(len(df)))).to_numpy()
        if features.shape[0] != n:
            raise ValueError(f"node_table has {features.shape[0]} rows but graph has {n} nodes")

    train_mask, val_mask, test_mask = _make_splits(split_cfg, n, gene, rng)

    return CascadeData(
        features=features,
        feature_names=feature_names,
        S=S,
        edge_index=edge_index,
        edge_weight=edge_weight,
        labels=labels,
        gene=gene,
        train_mask=train_mask,
        val_mask=val_mask,
        test_mask=test_mask,
        meta={
            "graph": graph,
            "num_nodes": n,
            "num_edges": int(S.nnz // 2),
            "nodes": nodes,
            "synthetic": synthetic,
            "split_mode": _cfg_get(split_cfg, "mode", "standard"),
            "seed": seed,
        },
    )
