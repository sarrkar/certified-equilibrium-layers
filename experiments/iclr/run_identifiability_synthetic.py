#!/usr/bin/env python3
"""Project 1 (ICLR): synthetic identifiability of concept latents.

Latent concept variables Z are generated by a latent linear SCM, mixed by the
KNOWN invertible propagation operator P_alpha and an unknown map G, then
recovered from interventional data. Reports the latent mean correlation
coefficient (MCC) and the Amari distance of the recovered mixing across three
regimes:

  - independent_hard:  identifiable base case (B = 0, single-gene hard
    interventions). Expected MCC near 1.
  - dense_hard:        dense linear SCM with hard interventions (open target for
    the current rank-one recovery; expected MCC well below 1).
  - soft_combinatorial: combinatorial soft interventions (open target).

Writes results/iclr/identifiability_synthetic.json and a PNG figure. Accepts
--seed and logs it (CLAUDE.md rule 3). Emits JSON and a figure only, never
LaTeX or prose (rule 7).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import scipy.sparse as sp

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "src"))

from identifiability.metrics import amari_distance, mean_correlation_coefficient  # noqa: E402
from identifiability.mixing import ObservationModel  # noqa: E402
from identifiability.recover import recover_latents, recover_mixing  # noqa: E402
from identifiability.scm import random_dag_scm  # noqa: E402

OUT = REPO / "results" / "iclr"


def symmetric_normalized_graph(d: int, edge_p: float, rng: np.random.Generator) -> sp.csr_matrix:
    """Random connected symmetric-normalized adjacency on d nodes."""
    w = rng.random((d, d)) * (rng.random((d, d)) < edge_p)
    w = np.triu(w, 1)
    for i in range(d):  # ring keeps it connected
        w[i, (i + 1) % d] = max(w[i, (i + 1) % d], 0.5)
    w = np.triu(w, 1)
    w = w + w.T
    deg = w.sum(axis=1)
    dinv = np.where(deg > 0, 1.0 / np.sqrt(deg), 0.0)
    return sp.csr_matrix(dinv[:, None] * w * dinv[None, :])


def _recover(scm, obs: ObservationModel, n: int, rng: np.random.Generator, soft: bool):
    z = scm.sample(n, rng)
    y = obs.observe(z)
    y_int = {}
    for i in range(scm.dim):
        if soft:
            intervened = scm.intervene_soft([i], mean_shift=0.0, var_scale=6.0)
        else:
            intervened = scm.intervene_hard(i, value_std=3.0)
        y_int[i] = obs.observe(intervened.sample(n, rng))
    w_hat = recover_mixing(y, y_int)
    z_hat = recover_latents(y, w_hat)
    return {
        "mcc": mean_correlation_coefficient(z, z_hat),
        "amari": amari_distance(obs.W, w_hat),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--dim", type=int, default=6, help="latent dimension / nodes")
    parser.add_argument("--n", type=int, default=20000, help="samples per condition")
    parser.add_argument("--alpha", type=float, default=0.2, help="propagation teleport")
    parser.add_argument("--edge-p", type=float, default=0.4, help="graph edge density")
    args = parser.parse_args()
    print(f"[identifiability] seed={args.seed} dim={args.dim} n={args.n} alpha={args.alpha}")

    rng = np.random.default_rng(args.seed)
    S = symmetric_normalized_graph(args.dim, args.edge_p, rng)
    obs = ObservationModel.from_graph(S, args.alpha, rng)

    regimes = {
        "independent_hard": _recover(
            random_dag_scm(args.dim, rng, edge_density=0.0), obs, args.n, rng, soft=False
        ),
        "dense_hard": _recover(
            random_dag_scm(args.dim, rng, edge_density=0.8, coef_scale=0.9),
            obs,
            args.n,
            rng,
            soft=False,
        ),
        "soft_combinatorial": _recover(
            random_dag_scm(args.dim, rng, edge_density=0.8, coef_scale=0.9),
            obs,
            args.n,
            rng,
            soft=True,
        ),
    }

    result = {
        "seed": args.seed,
        "dim": args.dim,
        "n": args.n,
        "alpha": args.alpha,
        "edge_p": args.edge_p,
        "metric": "MCC (higher=better, 1=identified up to affine); Amari (lower=better)",
        "regimes": regimes,
        "identified_base_case": bool(regimes["independent_hard"]["mcc"] > 0.95),
        "open_targets": ["dense_hard", "soft_combinatorial"],
    }
    OUT.mkdir(parents=True, exist_ok=True)
    out_path = OUT / "identifiability_synthetic.json"
    out_path.write_text(json.dumps(result, indent=2), encoding="utf-8")
    for name, m in regimes.items():
        print(f"[identifiability] {name:18s} MCC={m['mcc']:.4f} Amari={m['amari']:.4f}")
    print(f"[identifiability] wrote {out_path}")

    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt

        names = list(regimes)
        mccs = [regimes[k]["mcc"] for k in names]
        fig, ax = plt.subplots(figsize=(6, 4))
        ax.bar(names, mccs, color=["#2c7fb8", "#7fcdbb", "#edf8b1"])
        ax.axhline(0.95, ls="--", c="k", label="identified threshold")
        ax.set_ylabel("latent MCC")
        ax.set_ylim(0, 1.05)
        ax.set_title(f"Concept-latent identifiability (seed={args.seed}, d={args.dim})")
        ax.legend()
        fig.tight_layout()
        fig.savefig(OUT / "identifiability_synthetic.png", dpi=120)
        plt.close(fig)
        print(f"[identifiability] wrote {OUT / 'identifiability_synthetic.png'}")
    except ImportError:
        print("[identifiability] matplotlib not installed; skipped figure")
    return 0


if __name__ == "__main__":
    sys.exit(main())
